import { chromium, devices } from 'playwright';
const out = process.argv[2] ?? (await import('node:os')).tmpdir();
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] });
const ctx = await browser.newContext({ ...devices['iPhone 13'] });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://localhost:4173/');
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.getByTestId('power').tap();
await page.waitForFunction(() => window.__dm3?.runtime.getState().stemsReady, null, { timeout: 30000 });
await page.getByTestId('pane-screen').tap();
await page.getByTestId('tab-sources').tap();
await page.getByTestId('play-all').tap();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/m-screen.png` });
await page.getByTestId('pane-mix').tap();
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/m-mix.png` });
// drag channel 1 fader with touch-like pointer gesture
const box = await page.getByTestId('fader-ch1').boundingBox();
const before = await page.evaluate(() => window.__dm3.store.getState().console.channels.ch1.fader);
await page.mouse.move(box.x + box.width / 2, box.y + box.height * 0.62);
await page.mouse.down();
await page.mouse.move(box.x + box.width / 2, box.y + box.height * 0.3, { steps: 8 });
await page.mouse.up();
const after = await page.evaluate(() => window.__dm3.store.getState().console.channels.ch1.fader);
console.log('fader drag', before, '->', after);
const lvl = await page.evaluate(() => window.__dm3.engine.measure('listen', 500));
console.log('listen level', lvl.toFixed(1));
await page.getByTestId('pane-master').tap();
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/m-master.png` });
await page.setViewportSize({ width: 844, height: 390 });
await page.getByTestId('pane-mix').tap();
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/m-land.png` });
console.log('errors', errors);
await browser.close();
